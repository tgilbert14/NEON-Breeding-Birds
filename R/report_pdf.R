# ===========================================================================
# report_pdf.R: two-page server-side PDF site report (DP1.10003.001).
#
# Ported from the Small Mammal app's report_pdf.R approach: base grDevices plus
# base grid, streamed by a Shiny downloadHandler (output$reportPdf). No LaTeX, no
# headless browser, no extra packages. cairo_pdf is used when the build has
# cairo; plain pdf() is the fallback, and bpdf_text() maps the few typographic
# glyphs to ASCII and drops anything outside Latin-1 so neither device boxes a
# glyph. Sourced from global.R after R/bird_helpers.R.
#
# Every number comes from the same validated bundle and helpers the app shows:
# site_birds() / species_board() (prepare_site_bundle), chao2_points(),
# bird_accum(), bird_accumulation_verdict(), bird_qc(), the held ledger and the
# visit ledger. Values that can be unavailable print "n/a", never NA or 0.
#
# Verify without Shiny: Rscript --vanilla scripts/test_report_pdf.R
# ===========================================================================
suppressPackageStartupMessages(library(grid))

