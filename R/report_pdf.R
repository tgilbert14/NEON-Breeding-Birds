# ---- text helpers ------------------------------------------------------------
bpdf_text <- function(x) {
  x <- as.character(x)
  x[is.na(x)] <- "n/a"
  x <- gsub("—|–", "-", x)
  x <- gsub("‘|’", "'", x); x <- gsub("“|”", "\"", x)
  x <- gsub("≈", "~", x); x <- gsub("±", "+/-", x)
  x <- gsub("≥", ">=", x); x <- gsub("≤", "<=", x)
  x <- gsub("→", "to", x); x <- gsub("…", "...", x)
  enc2utf8(iconv(x, "UTF-8", "latin1", sub = ""))
}
bpdf_num <- function(x, digits = 2) {
  x <- suppressWarnings(as.numeric(x))
  ifelse(is.finite(x), formatC(x, format = "f", digits = digits, big.mark = ","), "n/a")
}
bpdf_int <- function(x) {
  x <- suppressWarnings(as.numeric(x))
  ifelse(is.finite(x), format(round(x), big.mark = ",", trim = TRUE), "n/a")
}
bpdf_y <- function(yTop) unit(1, "npc") - unit(yTop, "in")

# Measure-then-wrap; call only after the device is open.
bpdf_wrap <- function(txt, fontsize, width_in, fontface = 1) {
  gp <- gpar(fontsize = fontsize, fontface = fontface)
  words <- strsplit(txt, " ", fixed = TRUE)[[1]]; lines <- character(0); cur <- ""
  for (w in words) {
    test <- if (nzchar(cur)) paste(cur, w) else w
    wd <- convertWidth(grobWidth(textGrob(test, gp = gp)), "in", valueOnly = TRUE)
    if (wd > width_in && nzchar(cur)) { lines <- c(lines, cur); cur <- w } else cur <- test
  }
  c(lines, cur)
}
bpdf_para <- function(txt, yTop, fontsize = 9.5, col = BPDF$ink, fontface = 1,
                      gapAfter = 0.08, x_in = 0, width_in = BPDF$cw, bullet = FALSE) {
  lh <- BPDF$lineH * fontsize / 9.5
  indent <- if (bullet) 0.14 else 0
  lines <- bpdf_wrap(bpdf_text(txt), fontsize, width_in - indent, fontface)
  if (bullet)
    grid.text("-", x = unit(x_in, "in"), y = bpdf_y(yTop), just = c("left", "top"),
              gp = gpar(fontsize = fontsize, col = col))
  for (ln in lines) {
    grid.text(ln, x = unit(x_in + indent, "in"), y = bpdf_y(yTop), just = c("left", "top"),
              gp = gpar(fontsize = fontsize, col = col, fontface = fontface))
    yTop <- yTop + lh
  }
  yTop + gapAfter
}
bpdf_h <- function(txt, yTop, x_in = 0) {
  grid.text(bpdf_text(txt), x = unit(x_in, "in"), y = bpdf_y(yTop), just = c("left", "top"),
            gp = gpar(fontsize = 11, fontface = "bold", col = BPDF$rust))
  yTop + 0.23
}
# Truncate one line to a width so a long species name never overruns its column.
bpdf_fit <- function(txt, fontsize, width_in, fontface = 1) {
  txt <- bpdf_text(txt); gp <- gpar(fontsize = fontsize, fontface = fontface)
  wd <- function(s) convertWidth(grobWidth(textGrob(s, gp = gp)), "in", valueOnly = TRUE)
  if (wd(txt) <= width_in) return(txt)
  while (nchar(txt) > 1 && wd(paste0(txt, "...")) > width_in) txt <- substr(txt, 1, nchar(txt) - 1)
  paste0(trimws(txt), "...")
}

# ---- tiles and table -----------------------------------------------------------
# cells: list of list(value, label, note). Each tile is one column of the band.
bpdf_tiles <- function(cells, yTop, cellH = 0.86) {
  n <- length(cells); w <- BPDF$cw / n
  for (i in seq_len(n)) {
    x0 <- (i - 1) * w
    grid.rect(x = unit(x0 + 0.03, "in"), y = bpdf_y(yTop), width = unit(w - 0.06, "in"),
              height = unit(cellH, "in"), just = c("left", "top"), gp = gpar(fill = BPDF$tint, col = NA))
    grid.rect(x = unit(x0 + 0.03, "in"), y = bpdf_y(yTop), width = unit(0.04, "in"),
              height = unit(cellH, "in"), just = c("left", "top"), gp = gpar(fill = BPDF$rust, col = NA))
    inner <- w - 0.26
    v <- bpdf_text(cells[[i]]$value)
    vfs <- if (nchar(v) > 12) 11.5 else 17
    grid.text(bpdf_fit(v, vfs, inner, 2), x = unit(x0 + 0.17, "in"), y = bpdf_y(yTop + 0.09),
              just = c("left", "top"), gp = gpar(fontsize = vfs, fontface = "bold", col = BPDF$ink))
    yy <- yTop + 0.40
    for (ln in bpdf_wrap(bpdf_text(cells[[i]]$label), 8.2, inner)) {
      grid.text(ln, x = unit(x0 + 0.17, "in"), y = bpdf_y(yy), just = c("left", "top"),
                gp = gpar(fontsize = 8.2, col = BPDF$muted))
      yy <- yy + 0.135
    }
  }
  yTop + cellH + 0.10
}
bpdf_table <- function(cols, rows, colx, yTop, faces = rep(1, length(cols)), fs = 8.6,
                       rowH = 0.182, align = rep("left", length(cols))) {
  colw <- diff(c(colx, BPDF$cw)) - 0.08
  xpos <- function(j) if (align[j] == "right") colx[j] + colw[j] else colx[j]
  for (j in seq_along(cols))
    grid.text(bpdf_text(cols[j]), x = unit(xpos(j), "in"), y = bpdf_y(yTop), just = c(align[j], "top"),
              gp = gpar(fontface = "bold", fontsize = fs, col = BPDF$ink2))
  grid.lines(x = unit(c(0, BPDF$cw), "in"), y = bpdf_y(yTop + 0.16), gp = gpar(col = BPDF$line, lwd = 1))
  yTop <- yTop + 0.22
  for (i in seq_along(rows)) {
    if (i %% 2 == 0)
      grid.rect(x = unit(0, "in"), y = bpdf_y(yTop - 0.02), width = unit(BPDF$cw, "in"),
                height = unit(rowH, "in"), just = c("left", "top"), gp = gpar(fill = BPDF$zebra, col = NA))
    r <- rows[[i]]
    for (j in seq_along(r))
      grid.text(bpdf_fit(r[j], fs, colw[j], faces[j]), x = unit(xpos(j), "in"), y = bpdf_y(yTop),
                just = c(align[j], "top"), gp = gpar(fontsize = fs, fontface = faces[j], col = BPDF$ink))
    yTop <- yTop + rowH
  }
  yTop + 0.08
}

# ---- accumulation curve (pure grid) ------------------------------------------
bpdf_accum_chart <- function(ac, x_in, yTop, w_in, h_in) {
  if (is.null(ac) || !nrow(ac)) {
    grid.text("Not enough valid counts for a curve", x = unit(x_in + w_in / 2, "in"),
              y = bpdf_y(yTop + h_in / 2), gp = gpar(fontsize = 8.5, col = BPDF$muted))
    return(invisible())
  }
  xr <- c(0, max(ac$counts)); yr <- c(0, max(1, max(ac$richness)) * 1.08)
  pushViewport(viewport(x = unit(x_in + 0.48, "in"), y = bpdf_y(yTop + 0.10),
                        width = unit(w_in - 0.58, "in"), height = unit(h_in - 0.52, "in"),
                        just = c("left", "top"), xscale = xr, yscale = yr))
  grid.rect(gp = gpar(col = BPDF$line, fill = NA, lwd = 0.6))
  grid.polygon(x = unit(c(ac$counts[1], ac$counts, ac$counts[nrow(ac)]), "native"),
               y = unit(c(0, ac$richness, 0), "native"),
               gp = gpar(fill = "#f3e1d8", col = NA))
  grid.lines(x = unit(ac$counts, "native"), y = unit(ac$richness, "native"),
             gp = gpar(col = BPDF$rust, lwd = 2))
  grid.xaxis(gp = gpar(fontsize = 7, col = BPDF$ink2))
  grid.yaxis(gp = gpar(fontsize = 7, col = BPDF$ink2))
  grid.text("valid six-minute counts", y = unit(-0.36, "in"), gp = gpar(fontsize = 7.5, col = BPDF$muted))
  grid.text("species detected", x = unit(-0.38, "in"), rot = 90, gp = gpar(fontsize = 7.5, col = BPDF$muted))
  popViewport()
  invisible()
}

