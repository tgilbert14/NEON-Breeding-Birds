# bird_qc() per species, run on that species' rows only so each call prepares
# a small table (the full table per species took ~50 s at SRER).
bird_report_qc_summary <- function(obs, board, points = NULL) {
  empty <- data.frame(key = character(), level = character(), n = integer(),
                      n_species = integer(), stringsAsFactors = FALSE)
  if (is.null(board) || !nrow(board) || is.null(obs) || !nrow(obs)) return(empty)
  unit_col <- if ("communityScientificName" %in% names(obs)) obs$communityScientificName else obs$scientificName
  by_sp <- split(seq_len(nrow(obs)), unit_col)
  rows <- list()
  for (sci in board$scientificName) {
    idx <- by_sp[[sci]]; if (is.null(idx)) next
    q <- tryCatch(bird_qc(obs[idx, , drop = FALSE], sci, points), error = function(e) NULL)
    for (f in q$flags)
      rows[[length(rows) + 1L]] <- data.frame(key = f$key, level = f$level, n = as.integer(f$n),
                                               sci = sci, stringsAsFactors = FALSE)
  }
  if (!length(rows)) return(empty)
  d <- do.call(rbind, rows)
  lv_rank <- c(high = 1L, warn = 2L, info = 3L)
  out <- do.call(rbind, lapply(split(d, d$key), function(x) data.frame(
    key = x$key[1], level = x$level[order(lv_rank[x$level])][1], n = sum(x$n),
    n_species = length(unique(x$sci)), stringsAsFactors = FALSE)))
  out[order(lv_rank[out$level], -out$n), , drop = FALSE]
}
bird_report_held_summary <- function(held) {
  if (is.null(held) || !nrow(held) || !"hold_reason" %in% names(held))
    return(data.frame(hold_reason = character(), n = integer(), stringsAsFactors = FALSE))
  t <- sort(table(held$hold_reason), decreasing = TRUE)
  data.frame(hold_reason = names(t), n = as.integer(t), stringsAsFactors = FALSE)
}

# ---- page frame ------------------------------------------------------------------
bpdf_page <- function(page_i, running) {
  grid.newpage()
  pushViewport(viewport(width = unit(BPDF$cw, "in"), height = unit(BPDF$ch, "in"), name = "content"))
  if (page_i > 1) {
    grid.text(bpdf_fit(running, 10, BPDF$cw - 2.2, 2), x = unit(0, "in"), y = bpdf_y(0),
              just = c("left", "top"), gp = gpar(fontsize = 10, fontface = "bold", col = BPDF$ink))
    grid.text(sprintf("Breeding bird site report, page %d of 2", page_i), x = unit(BPDF$cw, "in"),
              y = bpdf_y(0), just = c("right", "top"), gp = gpar(fontsize = 8.5, col = BPDF$muted))
    grid.lines(x = unit(c(0, BPDF$cw), "in"), y = bpdf_y(0.22), gp = gpar(col = BPDF$line, lwd = 1))
  }
  fl <- bpdf_wrap(bpdf_text(BPDF_FOOT), 7, BPDF$cw)
  for (k in seq_along(fl))
    grid.text(fl[k], x = unit(0, "in"), y = unit((length(fl) - k) * 0.12, "in"),
              just = c("left", "bottom"), gp = gpar(fontsize = 7, col = BPDF$muted))
  BPDF$ch - length(fl) * 0.12 - 0.10    # lowest y the body may reach
}

# ---- the composer --------------------------------------------------------------
# site: four-letter code; site_name: full name. obs, held, visits, opportunity,
# points, board and sb are what ingest() commits to rv for a loaded site.
# Returns (invisibly) the bottom y of each page and the body limit, so tests can
# check nothing ran off a page.
render_bird_report_pdf <- function(file, site, site_name, obs, held, visits, opportunity,
                                   points, board, sb) {
  if (is.null(board)) board <- bird_empty_board()
  ch <- tryCatch(chao2_points(obs, visits), error = function(e) NULL)
  ac <- tryCatch(bird_accum(obs, visits), error = function(e) NULL)
  cov <- tryCatch(site_coverage(obs, visits), error = function(e) NA_real_)
  qc <- bird_report_qc_summary(obs, board, points)
  hs <- bird_report_held_summary(held)
  prepared <- bird_prepare_obs(obs)
  elig <- eligible_breeding_detections(prepared)
  sup_years <- opportunity$year[opportunity$supported %in% TRUE]
  years_txt <- if (length(sup_years)) {
    r <- range(sup_years); if (r[1] == r[2]) as.character(r[1]) else sprintf("%d to %d", r[1], r[2])
  } else "n/a"
  n_valid <- sum(visits$valid_count %in% TRUE)
  n_zero <- sum(visits$valid_count %in% TRUE & visits$outcome %in% "supported_zero")
  n_unavail <- sum(!(visits$valid_count %in% TRUE))
  n_without <- as.integer(sb$n_detections_without_count %||% 0L)
  n_read1 <- as.integer(sb$n_detections_count_read_as_one %||% 0L)
  read_caveat <- if (n_read1 > 0L)
    bird_cluster_read_caveat(site, sb$read_as_one_years, n_read1, sb$index_birds) else NULL
  running <- sprintf("%s · %s", site, site_name)

  BPDF_DEV(file, width = BPDF$w, height = BPDF$h, onefile = TRUE)
  on.exit(grDevices::dev.off(), add = TRUE)
  bottoms <- numeric(2)

  # ---------------- PAGE 1 ----------------
  limit <- bpdf_page(1, running)
  grid.rect(x = unit(0, "in"), y = bpdf_y(0), width = unit(BPDF$cw, "in"), height = unit(1.02, "in"),
            just = c("left", "top"), gp = gpar(fill = BPDF$rust_band, col = NA))
  grid.text(bpdf_fit(running, 16, BPDF$cw - 0.3, 2), x = unit(0.14, "in"), y = bpdf_y(0.13),
            just = c("left", "top"), gp = gpar(col = "white", fontsize = 16, fontface = "bold"))
  grid.text(bpdf_text(sprintf("NEON %s · %s · DOI %s", NEON_DPID, NEON_RELEASE, NEON_DOI)),
            x = unit(0.14, "in"), y = bpdf_y(0.48), just = c("left", "top"),
            gp = gpar(col = "white", fontsize = 9.5))
  grid.text(bpdf_text(sprintf("Breeding landbird point counts · years of record %s · generated %s",
                              years_txt, format(Sys.Date(), "%Y-%m-%d"))),
            x = unit(0.14, "in"), y = bpdf_y(0.70), just = c("left", "top"),
            gp = gpar(col = "#efe7d6", fontsize = 9))
  grid.lines(x = unit(c(0, BPDF$cw), "in"), y = bpdf_y(1.02), gp = gpar(col = BPDF$gold, lwd = 3))
  y <- 1.16
  y <- bpdf_para(sprintf(paste("Support: %s valid six-minute counts at %s points, including %s supported",
      "zeros (valid counts with no eligible detection). %s recorded counts were marked sampling",
      "impractical; they are unavailable, not zero."),
    bpdf_int(n_valid), bpdf_int(sb$n_points), bpdf_int(n_zero), bpdf_int(n_unavail)), y, 9.2, gapAfter = 0.10)

  top_freq <- if (nrow(board) && any(is.finite(board$detection_frequency)))
    board[which.max(board$detection_frequency), , drop = FALSE] else NULL
  cov_txt <- if (is.finite(cov)) sprintf("%.1f%%", 100 * cov) else "n/a"
  bpc_label <- if (n_without > 0L) "birds per count: unavailable here" else
    "birds per count, a detection index, not abundance"
  y <- bpdf_tiles(list(
    list(value = bpdf_int(sb$n_species),
         label = sprintf("species detected; incidence coverage %s", cov_txt)),
    list(value = if (n_without > 0L) "n/a" else bpdf_num(sb$birds_per_count, 2), label = bpc_label),
    list(value = if (is.null(top_freq)) "n/a" else
           if (!is.na(top_freq$vernacular) && nzchar(top_freq$vernacular)) top_freq$vernacular else
             top_freq$scientificName,
         label = if (is.null(top_freq)) "most frequently detected species" else
           sprintf("most frequently detected: on %s%% of valid counts",
                   bpdf_num(top_freq$detection_frequency, 0)))), y)
  idx_txt <- paste("Birds per count is the mean number of eligible birds per valid six-minute count.",
    "It is a detection index, not abundance or density: loud species are counted more readily than quiet ones.",
    "Flyovers are excluded.")
  if (n_without > 0L) idx_txt <- paste(idx_txt, sprintf(paste("It is unavailable here because %s eligible",
    "detections have no recorded cluster size, so the number of birds in them is unknown; they still count",
    "toward species and detection frequency."), bpdf_int(n_without)))
  y <- bpdf_para(idx_txt, y, 8.3, BPDF$muted, gapAfter = 0.04)
  if (!is.null(read_caveat)) y <- bpdf_para(read_caveat, y, 8.3, BPDF$muted, gapAfter = 0.04)
  y <- y + 0.06

  # Richness block: text on the left, accumulation curve on the right.
  y <- bpdf_h("Richness and sampling completeness", y)
  colw <- BPDF$cw * 0.52; chart_x <- colw + 0.15; chart_w <- BPDF$cw - chart_x; chart_h <- 1.95
  yl <- y
  chao_txt <- if (is.null(ch)) "Chao2: n/a. Fewer than two valid counts, so it is not estimable." else
    if (isTRUE(ch$unstable)) sprintf("Chao2 does not lead here: %s. Read the %s detected species and the coverage instead of a projected total.",
      ch$suppressed_reason %||% "the estimate is unstable", bpdf_int(ch$S_obs)) else
    sprintf("Bias-corrected Chao2 estimates %s species (95%% interval %s), from %s detected across %s valid counts. It is an extrapolation from incidence, not a census.",
      bpdf_num(ch$chao2, 0),
      if (is.finite(ch$ci_lo) && is.finite(ch$ci_hi)) sprintf("%s to %s", bpdf_num(ch$ci_lo, 0), bpdf_num(ch$ci_hi, 0)) else "n/a",
      bpdf_int(ch$S_obs), bpdf_int(ch$m))
  yl <- bpdf_para(chao_txt, yl, 9, width_in = colw, gapAfter = 0.08)
  verdict <- if (!is.null(ch) && ch$S_obs > 0L) bird_accumulation_verdict(ch$Q1, ch$m) else NULL
  if (!is.null(verdict)) yl <- bpdf_para(verdict$text, yl, 9, width_in = colw, gapAfter = 0.08)
  if (!is.null(ch) && ch$S_obs > 0L)
    yl <- bpdf_para(sprintf(paste("Support: %s species on exactly one count (Q1), %s on exactly two (Q2),",
      "out of %s valid counts. The curve is the mean over 40 random orderings of those counts;",
      "repeated counts at a point are repeated samples, not new places."),
      bpdf_int(ch$Q1), bpdf_int(ch$Q2), bpdf_int(ch$m)), yl, 8.3, BPDF$muted, width_in = colw)
  bpdf_accum_chart(ac, chart_x, y, chart_w, chart_h)
  y <- max(yl, y + chart_h) + 0.06

  y <- bpdf_h("Top 15 species by detection frequency", y)
  if (nrow(board)) {
    top <- head(board[order(-board$detection_frequency, -board$detections), , drop = FALSE], 15)
    rows <- lapply(seq_len(nrow(top)), function(i) c(
      top$vernacular[i], top$scientificName[i],
      paste0(bpdf_num(top$detection_frequency[i], 1), "%"),
      bpdf_int(top$detections[i]), bpdf_num(top$index[i], 2),
      ifelse(is.na(top$method[i]) | !nzchar(top$method[i]), "unknown", top$method[i])))
    y <- bpdf_table(c("Species", "Scientific name", "% of valid counts", "Detections", "Birds per count", "Method"),
                    rows, colx = c(0, 1.75, 3.45, 4.55, 5.35, 6.40) * BPDF$cw / 7.3, yTop = y,
                    faces = c(1, 3, 1, 1, 1, 1), align = c("left", "left", "right", "right", "right", "left"))
    y <- bpdf_para(paste("% of valid counts: share of valid six-minute counts with at least one eligible detection.",
      "Birds per count is the species' detection index; n/a means some of its detections have no usable count.",
      "Method is the most common recorded detection method."), y, 7.8, BPDF$muted, gapAfter = 0)
  } else {
    y <- bpdf_para("No eligible non-flyover species were detected on the valid counts here. That is a supported zero record, not proof of absence.", y, 9)
  }
  bottoms[1] <- y
  popViewport()

  # ---------------- PAGE 2 ----------------
  limit2 <- bpdf_page(2, running); y <- 0.42
  y <- bpdf_h("Quality checks: verify, not wrong", y)
  y <- bpdf_para(paste("Each flag marks detections worth checking against the source record. A flag is not a",
    "finding of error, and no flagged detection is removed from the counts in this report."), y, 8.6, BPDF$muted)
  if (nrow(qc)) {
    rows <- lapply(seq_len(nrow(qc)), function(i) c(
      bpdf_label(BPDF_QC_LABELS, qc$key[i]), qc$level[i],
      bpdf_int(qc$n[i]), bpdf_int(qc$n_species[i])))
    y <- bpdf_table(c("Flag", "Level", "Detections", "Species"), rows,
                    colx = c(0, 4.6, 5.5, 6.3) * BPDF$cw / 7.3, yTop = y,
                    align = c("left", "left", "right", "right"))
  } else y <- bpdf_para("No eligible detections were flagged.", y, 9)
  y <- y + 0.04

  y <- bpdf_h("Held records", y)
  y <- bpdf_para(paste("Held records stay in the site audit ledger but do not enter species counts, detection",
    "frequency, or the index, because a field the protocol needs is missing or out of range."), y, 8.6, BPDF$muted)
  if (nrow(hs)) {
    rows <- lapply(seq_len(nrow(hs)), function(i) c(
      bpdf_label(BPDF_HOLD_LABELS, hs$hold_reason[i]), hs$hold_reason[i], bpdf_int(hs$n[i])))
    y <- bpdf_table(c("Reason", "Code", "Records"), rows, colx = c(0, 3.9, 6.3) * BPDF$cw / 7.3,
                    yTop = y, faces = c(1, 1, 1), align = c("left", "left", "right"))
  } else y <- bpdf_para("No records are held at this site.", y, 9)
  y <- y + 0.04

  y <- bpdf_h("Distance usability", y)
  n_el <- if (is.null(elig)) 0L else nrow(elig)
  n_obs_d <- if (n_el) sum(elig$distance_state == "observed", na.rm = TRUE) else 0L
  y <- bpdf_para(sprintf(paste("%s of %s eligible detections (%s) carry an observed distance; the rest are",
      "sentinel, missing or invalid and stay out of the distance profile. The app's 0 to 200 m distance profile",
      "is relative: it shows where detections fell, not density, and it is not corrected for detectability."),
    bpdf_int(n_obs_d), bpdf_int(n_el),
    if (n_el) sprintf("%.1f%%", 100 * n_obs_d / n_el) else "n/a"), y, 9)
  y <- y + 0.04

  y <- bpdf_h("Site design notes", y)
  for (nt in bird_site_design_notes(site, visits)) y <- bpdf_para(nt, y, 8.8, bullet = TRUE, gapAfter = 0.03)
  y <- y + 0.06

  y <- bpdf_h("Caveats", y)
  share <- tryCatch(bird_coarse_record_share(obs, held), error = function(e) NULL)
  protected <- if (!is.null(share) && share$k > 0L) paste(BIRD_PROTECTED_CAVEAT, sprintf(
    "%s of %s bird records here are above species level, for protection or because the bird was not identified to species.",
    bpdf_int(share$k), bpdf_int(share$n))) else BIRD_PROTECTED_CAVEAT
  cav <- c("Birds per count is a detection index, not abundance, density, or a population estimate.",
           "A species not detected was not necessarily absent: a non-detection is not absence.",
           protected)
  if (!is.null(read_caveat)) cav <- c(cav, read_caveat)
  for (cv in cav) y <- bpdf_para(cv, y, 8.8, bullet = TRUE, gapAfter = 0.03)
  y <- y + 0.06

  y <- bpdf_h("Citation", y)
  y <- bpdf_para(BPDF_CITATION, y, 9)
  bottoms[2] <- y
  popViewport()
  invisible(list(file = file, bottoms = bottoms, limits = c(limit, limit2)))
}
